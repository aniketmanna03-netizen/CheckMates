function HighlightText({ text }) {
  // highlight [?uncertain?] and numbers+units, preserving original text
  const parts = [];
  const rx = /(\[\?[\s\S]*?\?\])|(\d+(?:[.,]\d+)?\s?(?:%|ml|mL|l\b|L\b|litres?|liters?|g\b|gm|kg|days?|hours?|hrs?|w\/w|w\/v|g\/l)?)/g;
  let last = 0, m, i = 0;
  while ((m = rx.exec(text))) {
    if (m.index > last) parts.push(text.slice(last, m.index));
    if (m[1]) parts.push(<span key={i++} className="unc-hl" title="Marked uncertain">{m[1].slice(2, -2)}</span>);
    else parts.push(<span key={i++} className="num-hl">{m[2]}</span>);
    last = m.index + m[0].length;
  }
  if (last < text.length) parts.push(text.slice(last));
  return <>{parts}</>;
}

function useSpeech() {
  const [speaking, setSpeaking] = useState(false);
  const [voices, setVoices] = useState([]);
  useEffect(() => {
    if (!('speechSynthesis' in window)) return;
    const load = () => setVoices(window.speechSynthesis.getVoices());
    load(); window.speechSynthesis.onvoiceschanged = load;
    return () => { window.speechSynthesis.cancel(); };
  }, []);
  const supported = 'speechSynthesis' in window;
  const voiceFor = (bcp) => voices.find((v) => v.lang === bcp) || voices.find((v) => v.lang && v.lang.slice(0, 2) === bcp.slice(0, 2));
  const speak = (text, bcp) => {
    if (!supported) return false;
    window.speechSynthesis.cancel();
    const u = new SpeechSynthesisUtterance(text); u.lang = bcp; u.rate = 0.92;
    const v = voiceFor(bcp); if (v) u.voice = v;
    u.onend = () => setSpeaking(false); u.onerror = () => setSpeaking(false);
    setSpeaking(true); window.speechSynthesis.speak(u); return true;
  };
  const stop = () => { supported && window.speechSynthesis.cancel(); setSpeaking(false); };
  return { supported, speaking, speak, stop, voiceFor };
}

function ItemCard({ it, exp, lang, t }) {
  const sevCls = it.severity === 'danger' ? ' sev-danger' : it.severity === 'caution' ? ' sev-caution' : '';
  const unclear = it.unclear || (exp && exp.unclear);
  return (
    <div className={'item' + sevCls}>
      <div className="orig">
        <div className="lbl"><Icon name="Quote" size={15} /><span className="mono">{t('original')}</span></div>
        {it.severity && (it.cat === 'warning' || it.cat === 'condition') && it.severity !== 'note' && (
          <div className={'sev-tag ' + it.severity}><Icon name={it.severity === 'danger' ? 'OctagonAlert' : 'TriangleAlert'} size={15} />{window.KL.severityLabel(lang, it.severity)}</div>
        )}
        <div className="txt" lang="und"><HighlightText text={it.source} /></div>
      </div>
      <div className="plain">
        <div className="lbl"><Icon name="MessageSquareText" size={15} /><span className="mono">{t('plain')}</span>
          {exp && exp.mode === 'ai' && !unclear && <Tip text="Generated by the explanation service from this line only. Numbers were checked against the original."><span className="chip chip-leaf" style={{ fontSize: 11, padding: '2px 8px' }}>AI · numbers checked</span></Tip>}
        </div>
        {unclear ? (
          <div className="txt" style={{ color: 'var(--amber)', fontWeight: 600, display: 'flex', gap: 8 }}><Icon name="CircleHelp" size={18} />{t('unable_verify')}</div>
        ) : !exp ? (
          <div className="txt muted">—</div>
        ) : exp.mode === 'ai' ? (
          <div className="txt" lang={lang}>{exp.plain}</div>
        ) : (
          <div className="txt" lang={lang} style={{ fontSize: 15.5, color: 'var(--ink-2)' }}>{exp.plain} <span style={{ display: 'block', marginTop: 6, fontFamily: 'var(--mono)', fontSize: 14, color: 'var(--ink)' }}>“{exp.quote}”</span></div>
        )}
        {exp && exp.note && <div style={{ marginTop: 10, fontSize: 13.5, color: 'var(--amber)', display: 'flex', gap: 6 }}><Icon name="ShieldAlert" size={15} />{exp.note}</div>}
      </div>
    </div>
  );
}

function Section({ icon, title, count, children, tone }) {
  return (
    <section className="res-sec">
      <div className="res-sec-h">
        <span style={{ width: 40, height: 40, borderRadius: 12, display: 'grid', placeItems: 'center', background: tone === 'amber' ? 'var(--amber-bg)' : 'var(--leaf-soft)', color: tone === 'amber' ? 'var(--amber)' : 'var(--forest)' }}><Icon name={icon} /></span>
        <h2>{title}</h2>
        {count != null && <span className="count">{count}</span>}
      </div>
      {children}
    </section>
  );
}

function ResultsPage() {
  const { parts } = useRouter();
  const { lang, setLang, t } = useLang();
  const toast = useToast();
  const id = parts[1];
  const [rec, setRec] = useState(() => window.KL.getScan(id));
  const [busy, setBusy] = useState(false);
  const [bprog, setBprog] = useState(0);
  const [showImg, setShowImg] = useState(false);
  const [showLang, setShowLang] = useState(false);
  const [rulesOnly, setRulesOnly] = useState(() => localStorage.getItem('kl.rulesOnly') === '1');
  const speech = useSpeech();
  const linfo = window.KL_I18N.langInfo(lang);

  useEffect(() => { setRec(window.KL.getScan(id)); }, [id]);
  const exp = rec && rec.explanations && rec.explanations[lang + (rulesOnly ? ':rules' : '')];

  const runExplain = async (force) => {
    if (!rec || busy) return;
    const key = lang + (rulesOnly ? ':rules' : '');
    if (!force && rec.explanations && rec.explanations[key]) return;
    setBusy(true); setBprog(0);
    try {
      const parsed = window.KL.parseLabel(rec.text, rec.ocr ? rec.ocr.lowConf : []);
      const e = await window.KL.explain(parsed, lang, { mode: rulesOnly ? 'rules' : 'auto', onProgress: setBprog });
      const next = { ...rec, parsed, status: 'explained', lang, explanations: { ...(rec.explanations || {}), [key]: e } };
      const r = window.KL.saveScan(next);
      if (!r.ok) toast(r.error);
      setRec(next);
    } catch (err) { toast('Explanation failed: ' + (err.message || err)); }
    setBusy(false);
  };
  useEffect(() => { runExplain(false); }, [id, lang, rulesOnly, !!rec]);

  if (!rec) {
    return (
      <div className="page route-fade"><div className="wrap-narrow empty">
        <span className="ring"><Icon name="FileQuestion" size={44} /></span>
        <h1 style={{ fontSize: 40 }}>Scan not found</h1>
        <p className="muted" style={{ maxWidth: 460 }}>This result isn't saved on this device. It may have been deleted, or it was created on another phone or browser.</p>
        <div style={{ display: 'flex', gap: 10, flexWrap: 'wrap', justifyContent: 'center' }}><Link to="/scan" className="btn btn-primary"><Icon name="ScanLine" />{t('new_scan')}</Link><Link to="/history" className="btn btn-soft">{t('nav_history')}</Link></div>
      </div></div>
    );
  }

  const p = rec.parsed;
  const byCat = (c) => p.items.filter((i) => i.cat === c);
  const ins = byCat('instruction'), warns = byCat('warning'), conds = byCat('condition');
  const unclearItems = p.items.filter((i) => i.unclear || (exp && exp.items[i.id] && exp.items[i.id].unclear));
  const missing = p.checklist.filter((c) => !c.found);
  const prodFields = [['product', 'Product name'], ['ingredient', 'Active ingredient'], ['concentration', 'Concentration & units'], ['manufacturer', 'Manufacturer'], ['registration', 'Registration details']];

  const speakAll = () => {
    if (speech.speaking) { speech.stop(); return; }
    if (!exp) return;
    const lines = [];
    [...ins, ...warns, ...conds].forEach((it) => {
      const e = exp.items[it.id];
      if (!e || e.unclear) lines.push(t('unable_verify'));
      else if (e.mode === 'ai') lines.push(e.plain);
      else lines.push(it.source);
    });
    const ok = speech.speak(lines.join('. '), exp.mode === 'ai' ? linfo.bcp : 'en-IN');
    if (!ok) toast('Read-aloud is not supported in this browser.');
    else if (!speech.voiceFor(linfo.bcp) && lang !== 'en') toast('No ' + linfo.name + ' voice installed on this device — pronunciation may be poor.');
  };
  const download = () => {
    const txt = window.KL.buildReport(rec, exp);
    const blob = new Blob([txt], { type: 'text/plain;charset=utf-8' });
    const a = document.createElement('a'); a.href = URL.createObjectURL(blob);
    a.download = 'Kissan-Drishti-report-' + (rec.name || rec.id).replace(/[^\w\-]+/g, '_').slice(0, 40) + '.txt';
    document.body.appendChild(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(a.href), 2000);
  };
  const share = async () => {
    const txt = window.KL.buildReport(rec, exp);
    if (navigator.share) { try { await navigator.share({ title: 'Kissan Drishti label report', text: txt }); return; } catch (e) { if (e.name === 'AbortError') return; } }
    try { await navigator.clipboard.writeText(txt); toast('Report text copied — no photo included.'); } catch (e) { toast('Could not copy. Use Download instead.'); }
  };

  return (
    <div className="page route-fade" data-screen-label="Results">
      <div className="wrap">
        <div className="page-head">
          <div>
            <div className="crumbs"><Link to="/history">{t('nav_history')}</Link><span>/</span><span>{new Date(rec.createdAt).toLocaleDateString()}</span></div>
            <h1>{rec.name || (p.product.product ? p.product.product.value : 'Label result')}</h1>
          </div>
          <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap' }}>
            {rec.isSample && <span className="chip chip-amber" style={{ fontSize: 14, padding: '8px 14px' }}><Icon name="FlaskConical" size={16} />Sample data · fictional</span>}
            <span className="chip" style={{ fontSize: 14, padding: '8px 14px' }}><Icon name="Languages" size={16} />Explaining in {linfo.native}</span>
            <Link to={'/products?labelText=' + encodeURIComponent(rec.text)} className="btn btn-soft btn-sm"><Icon name="Search" size={17} />Compare with product sources</Link>
          </div>
        </div>

        <div className="res-layout">
          <aside className="res-side">
            {rec.thumb ? (
              <button className="thumb" onClick={() => setShowImg(true)} style={{ border: 0, padding: 0 }} aria-label={t('view_label')}>
                <img src={rec.thumb} alt="Scanned label" />
              </button>
            ) : (
              <div className="thumb" style={{ padding: 20, textAlign: 'center' }}><Icon name="Keyboard" size={28} /><p className="muted" style={{ fontSize: 14, marginTop: 6 }}>{rec.manual ? 'Text entered manually' : 'Photo not saved'}</p></div>
            )}
            <div className="res-actions">
              <Link to={'/scan?edit=' + rec.id} className="btn btn-soft btn-sm"><Icon name="PencilLine" size={18} />{t('edit_text')}</Link>
              <button className="btn btn-soft btn-sm" onClick={() => setShowImg(true)}><Icon name="Image" size={18} />{t('view_label')}</button>
              <button className="btn btn-soft btn-sm" onClick={() => setShowLang(true)}><Icon name="Languages" size={18} />{t('change_lang')}</button>
              <button className="btn btn-soft btn-sm" onClick={() => runExplain(true)} disabled={busy}><Icon name="RefreshCw" size={18} />{t('explain_again')}</button>
              <button className="btn btn-soft btn-sm" onClick={speakAll} disabled={!exp || !speech.supported}><Icon name={speech.speaking ? 'Square' : 'Volume2'} size={18} />{speech.speaking ? 'Stop' : t('listen')}</button>
              <button className="btn btn-soft btn-sm" onClick={download}><Icon name="Download" size={18} />{t('download')}</button>
              <button className="btn btn-soft btn-sm" onClick={share}><Icon name="Share2" size={18} />Share text</button>
              <Link to="/scan" className="btn btn-primary btn-sm"><Icon name="ScanLine" size={18} />{t('new_scan')}</Link>
            </div>
            <label style={{ display: 'flex', gap: 10, alignItems: 'center', fontSize: 14, padding: '6px 4px', cursor: 'pointer' }}>
              <input type="checkbox" checked={rulesOnly} onChange={(e) => { setRulesOnly(e.target.checked); localStorage.setItem('kl.rulesOnly', e.target.checked ? '1' : '0'); }} style={{ width: 20, height: 20, accentColor: 'var(--forest)' }} />
              Rule-based only (no AI)
            </label>
          </aside>

          <div>
            {busy && (
              <div className="card processing" style={{ marginBottom: 30 }}>
                <div style={{ display: 'flex', gap: 12, alignItems: 'center' }}><div className="spinner" style={{ color: 'var(--leaf)' }} /><b>Explaining confirmed text in {linfo.name}…</b></div>
                <div className="pbar"><i style={{ width: Math.max(8, bprog * 100) + '%' }} /></div>
                <p className="muted" style={{ fontSize: 14 }}>Only the text you confirmed is sent. Each explanation is checked so numbers match the original.</p>
              </div>
            )}
            {exp && (
              <div style={{ marginBottom: 30, display: 'grid', gap: 10 }}>
                {exp.mode === 'ai' ? (
                  <Alert tone="info" icon="Sparkles"><b>AI explanation · {linfo.name}.</b> Generated only from your confirmed text, with every number checked against the original. It has not been independently verified — rely on the original wording and the physical label.{lang !== 'en' && ' Explanations in Indian languages may contain wording errors; chemical names are kept in original spelling.'}</Alert>
                ) : (
                  <Alert tone="neutral" icon="ListChecks"><b>{exp.notice === 'ai-unconfigured' ? 'AI explanation service not configured.' : exp.notice === 'ai-unavailable' ? 'AI explanation unavailable. Rule-based mode.' : 'Rule-based mode.'}</b> {window.KL.rb(lang, 3)}</Alert>
                )}
                {exp.errors && exp.errors.length > 0 && <Alert tone="amber">{exp.errors[0]}</Alert>}
              </div>
            )}

            <Section icon="Package" title={t('res_product')}>
              <div className="prod-grid">
                {prodFields.map(([k, n]) => (
                  <div className="prod-cell" key={k}>
                    <span className="mono muted">{n}</span>
                    {p.product[k] ? <span className="v" lang="und">{p.product[k].value}</span> : <span className="nf">{t('not_found')}</span>}
                  </div>
                ))}
              </div>
              <p className="muted" style={{ fontSize: 14, marginTop: 10 }}>Shown only if the field appears in the supplied text. Kissan Drishti cannot check registration status or product authenticity.</p>
            </Section>

            <Section icon="ListOrdered" title={t('res_instructions')} count={ins.length}>
              {ins.length ? ins.map((it) => <ItemCard key={it.id} it={it} exp={exp && exp.items[it.id]} lang={lang} t={t} />) : <Alert tone="neutral">{t('not_found')}</Alert>}
            </Section>

            <Section icon="TriangleAlert" title={t('res_warnings')} count={warns.length} tone="amber">
              {warns.length ? warns.map((it) => <ItemCard key={it.id} it={it} exp={exp && exp.items[it.id]} lang={lang} t={t} />) : <Alert tone="neutral">{t('not_found')}</Alert>}
              {warns.length > 0 && <p className="muted" style={{ fontSize: 14 }}>Red and amber tags appear only when the label itself uses words like “Danger”, “Poison”, “Caution” or “Warning”. Severity is never inferred.</p>}
            </Section>

            <Section icon="ClipboardList" title={t('res_conditions')} count={conds.length}>
              {conds.length ? conds.map((it) => <ItemCard key={it.id} it={it} exp={exp && exp.items[it.id]} lang={lang} t={t} />) : <Alert tone="neutral">{t('not_found')}</Alert>}
            </Section>

            <Section icon="CircleHelp" title={t('res_unclear')} tone="amber">
              <div style={{ display: 'grid', gap: 12 }}>
                {(unclearItems.length > 0 || p.marked.length > 0) && (
                  <Alert tone="amber"><b>{t('unable_verify')}</b> Check these against the physical label:
                    <div className="chips" style={{ marginTop: 10 }}>
                      {p.marked.map((m, i) => <span key={'m' + i} className="chip chip-amber">{m}</span>)}
                      {unclearItems.filter((u) => !p.marked.some((m) => u.source.includes(m))).map((u) => <span key={u.id} className="chip chip-amber">{u.source.slice(0, 50)}{u.source.length > 50 ? '…' : ''}</span>)}
                    </div>
                  </Alert>
                )}
                {p.lowConf.length > 0 && (
                  <Alert tone="amber" icon="ScanEye"><b>OCR was unsure about these words</b> and they were not changed during review:
                    <div className="chips" style={{ marginTop: 10 }}>{p.lowConf.map((w) => <span key={w} className="chip">{w}</span>)}</div>
                  </Alert>
                )}
                <div>
                  <p style={{ fontWeight: 600, margin: '8px 0 10px' }}>Common label sections — were they in the supplied text?</p>
                  <div className="missing-list">
                    {p.checklist.map((c) => (
                      <div key={c.key} className={'missing' + (c.found ? ' found' : '')}>
                        <Icon name={c.found ? 'CircleCheck' : 'CircleDashed'} style={{ color: c.found ? 'var(--leaf)' : 'var(--amber)' }} />
                        <div><b style={{ fontWeight: 600 }}>{c.label}</b><p className="muted" style={{ fontSize: 14 }}>{c.found ? 'Mentioned in the text' : t('not_found')}</p></div>
                      </div>
                    ))}
                  </div>
                  {missing.length > 0 && <p className="muted" style={{ fontSize: 14, marginTop: 10 }}>Missing sections may be on another side of the container, or were not captured. Kissan Drishti will not fill them in.</p>}
                </div>
              </div>
            </Section>

            {p.glossary.length > 0 && (
              <Section icon="BookOpen" title="Terms on this label">
                <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit,minmax(260px,1fr))', gap: 10 }}>
                  {p.glossary.map((g) => (
                    <div key={g.term} className="card card-pad"><b className="mono" style={{ fontSize: 14 }}>{g.term}</b><p style={{ marginTop: 6 }} lang={lang === 'hi' ? 'hi' : 'en'}>{lang === 'hi' ? g.hi : g.en}</p></div>
                  ))}
                </div>
                <p className="muted" style={{ fontSize: 14, marginTop: 10 }}>General term definitions from a fixed glossary — they describe the term, not your product.</p>
              </Section>
            )}

            <Disclaimer />
          </div>
        </div>

        {showImg && (
          <Modal onClose={() => setShowImg(false)} label={t('view_label')}>
            <h3 style={{ fontSize: 26, marginBottom: 16 }}>{t('view_label')}</h3>
            {rec.thumb ? <img src={rec.thumb} alt="Scanned label" style={{ width: '100%', borderRadius: 12 }} /> : <p className="muted">No photo was saved for this scan.</p>}
            <p className="mono muted" style={{ margin: '20px 0 8px' }}>Confirmed text</p>
            <div className="ocr-out">{rec.text}</div>
          </Modal>
        )}
        {showLang && (
          <Modal onClose={() => setShowLang(false)} label={t('change_lang')}>
            <h3 style={{ fontSize: 26, marginBottom: 6 }}>{t('change_lang')}</h3>
            <p className="muted" style={{ marginBottom: 16 }}>The original label wording stays unchanged. Only the explanation language changes.</p>
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit,minmax(150px,1fr))', gap: 8 }}>
              {window.KL_I18N.LANGS.map((l) => (
                <button key={l.code} className={'btn ' + (l.code === lang ? 'btn-primary' : 'btn-soft')} onClick={() => { setLang(l.code); setShowLang(false); }}><span lang={l.code}>{l.native}</span></button>
              ))}
            </div>
          </Modal>
        )}
      </div>
    </div>
  );
}

Object.assign(window, { ResultsPage });
